# Set operations
# Create two hardcoded lists of programming languages
languages1 = {'Python','Java','C','JavaScript','C#'}
languages2 = {'Python','C#',"C++","Java","JavaScript","JSON","R"}
# Print the union
print(languages1.union(languages2))
# Print the intersection
print(languages1.intersection(languages2))
# Print the difference
print(languages1.difference(languages2))